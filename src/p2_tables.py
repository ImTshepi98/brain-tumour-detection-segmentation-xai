"""PLAN2 P6/P7 tables: val and test side by side, from eval_p2.py outputs.
python src/p2_tables.py VAL_EVAL_DIR [TEST_EVAL_DIR] > reports/p2/tables.md
Every PLAN2 number in the dissertation comes from this file. A missing test dir prints '-' in its column."""
import json, sys
from pathlib import Path

CELLS = ("B+r", "B+p", "I+p", "B-r", "B-s", "I-r", "I-s")
KEY = {  # check -> how to compress its value dict for the side-by-side table
    "S1": lambda v: f"{v['neg_B_vs_I']:.3f} / {v['pastedpos_B_vs_I']:.3f}",
    "S2": lambda v: f"TNR gap {v['tnr_gap']:.3f}, TPR gap {v['tpr_gap']:.3f}",
    "S3": lambda v: f"{v['Bpr_vs_Br']:.3f} / {v['Ip_vs_Ir']:.3f}",
    "S4": lambda v: f"{v['share_below_after']:.1%} of {v['n']}, " + (
        f"{v['median_logit_change']:+.1f} logit" if "median_logit_change" in v else f"{v['median_volume_change_ml']:+.0f} mL"),
    "S5": lambda v: f"{v['brats']:.1%} / {v['ixi']:.1%}",
    "S6": lambda v: f"{v['brats']:.1%} / {v['ixi']:.1%}" + (
        f"; {v['brats_median_abs_logit_change']:.2f} / {v['ixi_median_abs_logit_change']:.2f} logit"
        if "brats_median_abs_logit_change" in v else ""),
    "S7": lambda v: "n/a" if v == "n/a" else "; ".join(
        f"{m} ratio {v[m]['median_tumour_ratio']:.2f}, out {v[m]['median_outside_mass']:.2f}, p {v[m]['deletion_p']:.2f}"
        for m in ("gradcam", "occlusion")),
    "S8": lambda v: ", ".join(f"{c} {v[c]['crossings']:.1%}" for c in ("B+r", "B-r", "I-r")),
    "S9": lambda v: " / ".join(f"{x:.3f}" for x in v.values()) if isinstance(v, dict) else str(v),
    "G1": lambda v: f"{v['B-r']:.2f} / {v['I-r']:.2f} mL",
}


def load(d, split):
    if d is None:
        return None
    d = Path(d)
    r = json.loads((d / f"results_{split}.json").read_text())
    s6 = d / f"s6_sensitivity_{split}.json"
    r["_s6"] = json.loads(s6.read_text()) if s6.exists() else None
    x = d / "xai" / "xai_summary.json"
    r["_xai"] = json.loads(x.read_text()) if x.exists() else None
    return r


def f3(x):
    return "-" if x is None else f"{x:.3f}"


def res(c):
    return {True: "PASS", False: "FAIL", None: "n/a"}[c["passed"]]


def main(val_dir, test_dir=None):
    R = {"val": load(val_dir, "val"), "test": load(test_dir, "test")}
    sp = [s for s in ("val", "test") if R[s]]
    P = print
    P("# PLAN2 tables (`p2-main`)\n")
    P("Generated by `src/p2_tables.py` from `eval_p2.py` outputs (val: `brats-dual-p2-eval-main-r10-val`; test: "
      "`brats-dual-p2-eval-main-r10-test`, read once). Checkpoint epoch "
      f"{R['val']['epoch']}, protocol `{R['val']['protocol_hash'][:12]}`; thresholds fixed on val: head "
      f"{R['val']['threshold_head']}, segmentation-derived v* {R['val']['threshold_seg']} mL.\n")

    P("## Verdict\n\n| Detector | " + " | ".join(sp) + " |\n|---|" + "---|" * len(sp))
    for det in ("head", "seg"):
        cells = []
        for s in sp:
            v = R[s]["verdict"][det]
            cells.append("shortcut-controlled" if v["shortcut_controlled"] else
                         "not shortcut-controlled (failed " + ", ".join(v["failed_must"]) + ")")
        P(f"| {'Detection head' if det == 'head' else 'Segmentation-derived'} | " + " | ".join(cells) + " |")

    P("\n## Detection (hemispheres; balanced accuracy per dataset, Brodersen et al. 2010; worst group, "
      "Sagawa et al. 2020)\n")
    P("| Detector | split | n | worst-group BA | BA BraTS | BA IXI | recall | specificity | F1 | AUROC |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    for det in ("head", "seg"):
        for s in sp:
            d = R[s][f"detection_{det}"]
            a = d["all"]
            P(f"| {det} | {s} | {R[s]['n']} | {f3(d['worst_group_ba'])} | {f3(d['brats']['balanced_accuracy'])} | "
              f"{f3(d['ixi']['balanced_accuracy'])} | {f3(a['recall'])} | {f3(a['specificity'])} | {f3(a['f1'])} | "
              f"{f3(a['auroc'])} |")

    P("\n## Share called 'tumour' per cell\n")
    P("| Detector | split | " + " | ".join(CELLS) + " |\n|---|---|" + "---|" * len(CELLS))
    for det in ("head", "seg"):
        for s in sp:
            c = R[s][f"detection_{det}"]["cells"]
            P(f"| {det} | {s} | " + " | ".join(f"{c[k]['positive_rate']:.3f} (n={c[k]['n']})" for k in CELLS) + " |")

    for det, name in (("head", "Detection head"), ("seg", "Segmentation-derived detector")):
        P(f"\n## Checks: {name}\n\n| Check | Tier | " + " | ".join(sp) + " |\n|---|---|" + "---|" * len(sp))
        ids = [c["id"] for c in R["val"]["checks"][det]]
        for cid in ids:
            row, tier = [], ""
            for s in sp:
                c = next(c for c in R[s]["checks"][det] if c["id"] == cid)
                tier = c["tier"]
                try:
                    val = KEY[cid](c["value"])
                except (KeyError, TypeError):
                    val = json.dumps(c["value"])
                row.append(f"{res(c)}: {val}")
            P(f"| {cid} | {tier} | " + " | ".join(row) + " |")

    if any(R[s]["_s6"] for s in sp):
        P("\n## S6 on shams >= 1 mL (labelled sensitivity analysis, not pre-registered)\n")
        P("| Detector | split | shams dropped (B-s / I-s) | crossings BraTS (n) | crossings IXI (n) | would pass |")
        P("|---|---|---|---|---|---|")
        for det in ("head", "seg"):
            for s in sp:
                x = R[s]["_s6"]
                if not x:
                    continue
                v = x[det]["value"]
                P(f"| {det} | {s} | {x['shams_dropped']['B-s']} / {x['shams_dropped']['I-s']} | {v['brats']:.1%} "
                  f"({v['brats_n']}) | {v['ixi']:.1%} ({v['ixi_n']}) | {'yes' if x[det]['passed'] else 'no'} |")

    P("\n## Segmentation (pass A on real BraTS tumours B+r; pass B WT)\n")
    P("| split | ET DSC | TC DSC | WT DSC | WT HD95 median mm | pass-B WT DSC B+r / B+p / I+p | pass-B FP mL median B-r / I-r |")
    P("|---|---|---|---|---|---|---|")
    for s in sp:
        g = R[s]["segmentation"]
        b = g["B+r"]
        P(f"| {s} | {b['dsc_ET']['mean']:.3f} | {b['dsc_TC']['mean']:.3f} | {b['dsc_WT']['mean']:.3f} | "
          f"{b['hd95_WT']['median']:.1f} | {b['dsc_WT_passB']['mean']:.3f} / {g['B+p']['dsc_WT_passB']['mean']:.3f} / "
          f"{g['I+p']['dsc_WT_passB']['mean']:.3f} | {g['fp_volume_passB_B-r']['median']:.2f} / "
          f"{g['fp_volume_passB_I-r']['median']:.2f} |")

    P("\n## Whole scans (both hemispheres; BraTS has no tumour-free scans, so specificity is IXI only)\n")
    P("| Detector | split | BraTS recall (n) | IXI specificity (n) |\n|---|---|---|---|")
    for det in ("head", "seg"):
        for s in sp:
            w = R[s][f"whole_scan_{det}"]
            P(f"| {det} | {s} | {w['recall']:.3f} ({w['brats_scans']}) | {w['specificity']:.3f} ({w['ixi_scans']}) |")

    if any(R[s]["_xai"] for s in sp):
        P("\n## XAI comparison (60 cases per split; deletion lower = better, insertion higher = better)\n")
        P("| Method | split | deletion AUC (random) | insertion AUC (random) | tumour ratio | outside-brain mass | "
          "pointing | sanity stage 1 / 2 | s per case |")
        P("|---|---|---|---|---|---|---|---|---|")
        for m in ("gradcam", "gradcam_old", "occlusion", "shap", "lime"):
            for s in sp:
                x = R[s]["_xai"]
                if not x or m not in x:
                    continue
                v, sm = x[m], x.get("sanity_median", {})
                san = (f"{sm[m + '_stage1']:.2f} / {sm[m + '_stage2']:.2f}" if m + "_stage1" in sm else "-")
                P(f"| {m} | {s} | {v['deletion_auc']:.3f} ({v['deletion_auc_random']:.3f}) | {v['insertion_auc']:.3f} "
                  f"({v['insertion_auc_random']:.3f}) | {v['tumour_ratio_median']:.2f} | {v['outside_mass_median']:.2f} | "
                  f"{v['pointing_rate']:.2f} | {san} | {v['seconds_median']:.2f} |")

    P("\n## Inference\n")
    for s in sp:
        i = R[s]["inference"]
        P(f"- {s}: {i['ms_mean']:.1f} ± {i['ms_sd']:.1f} ms per hemisphere pair ({i['passes']}; {i['device']}).")


if __name__ == "__main__":
    main(*sys.argv[1:3])
